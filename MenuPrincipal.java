    private void btnContinuarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnContinuarActionPerformed
        // TODO add your handling code here:
        // Leer lo que el usuario escribió en la caja de texto y quitar espacios
        String opcion = txtOpcion.getText().trim();

        switch (opcion) {
            case "1":
                // Abrir ventana de Depósito y cerrar el menú actual
                new VentanaDeposito().setVisible(true);
                this.dispose();
                break;

            case "2":
                // Abrir ventana de Retiro y cerrar el menú actual
                new VentanaRetiro().setVisible(true);
                this.dispose();
                break;

            default:
                // Mensaje si escriben otra cosa distinta a 1 o 2
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese una opción válida (1 o 2).", "Opción inválida", javax.swing.JOptionPane.WARNING_MESSAGE);
                txtOpcion.setText("");
                break;
        }           
                    
            
    
    
    }//GEN-LAST:event_btnContinuarActionPerformed
    
