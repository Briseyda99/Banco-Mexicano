    private void btnDepositarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDepositarActionPerformed
        // TODO add your handling code here:
        try {
            // 1. Leer la cantidad escrita en la caja de texto y convertirla a número
            double cantidad = Double.parseDouble(txtCantidadDeposito.getText().trim());

            if (cantidad > 0) {
                // 2. Sumar el depósito a la clase Cuenta
                Cuenta.depositar(cantidad);

                // 3. Mostrar la ventana emergente con opciones Sí y No
                Object[] opciones = {"Si", "No"};
                int respuesta = javax.swing.JOptionPane.showOptionDialog(
                        this,
                        "¿Desea realizar otro depósito?",
                        "Depósito",
                        javax.swing.JOptionPane.YES_NO_OPTION,
                        javax.swing.JOptionPane.QUESTION_MESSAGE,
                        null,
                        opciones,
                        opciones[0]
                );

                if (respuesta == javax.swing.JOptionPane.YES_OPTION) {
                    // Si elige "Si": limpia la caja y se queda en la pantalla de Depósito
                    txtCantidadDeposito.setText("");
                    txtCantidadDeposito.requestFocus();
                } else {
                    // Si elige "No": regresa al Menú Principal y cierra Depósito
                    new MenuPrincipal().setVisible(true);
                    this.dispose();
                }

            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a cero.", "Monto inválido", javax.swing.JOptionPane.WARNING_MESSAGE);
                txtCantidadDeposito.setText("");
            }

        } catch (NumberFormatException e) {
            // Por si el usuario deja la caja vacía o escribe letras
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, ingrese una cantidad numérica válida.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            txtCantidadDeposito.setText("");
        }
    }//GEN-LAST:event_btnDepositarActionPerformed

